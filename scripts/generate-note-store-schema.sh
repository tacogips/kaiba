#!/usr/bin/env bash
# Regenerates the note-store DDL from the nodetto ERD
# (design-docs/specs/note-store-schema-v25.md).
#
#   scripts/generate-note-store-schema.sh          # rewrite both outputs
#   scripts/generate-note-store-schema.sh --check  # exit 1 when either is stale
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
erd="$root/schema/note-store.erd.jsonl"
sql="$root/schema/note-store.sqlite.sql"
swift="$root/Sources/AppCore/NoteStoreSchemaDDL.generated.swift"

if ! command -v nodetto-cli >/dev/null 2>&1; then
  echo "nodetto-cli is required (brew install --cask tacogips/tap/nodetto)" >&2
  exit 2
fi

render_swift() {
  local source="$1"
  if grep -q '"""#' "$source"; then
    echo "generated SQL contains the Swift raw-string terminator" >&2
    exit 2
  fi
  printf '%s\n' \
    '// Generated by scripts/generate-note-store-schema.sh from schema/note-store.sqlite.sql.' \
    '// Do not edit: change schema/note-store.erd.jsonl and run `mise run schema:generate`.' \
    '' \
    'let noteStoreSchemaSQL = #"""'
  cat "$source"
  printf '%s\n' '"""#'
}

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
if ! output="$(nodetto-cli ddl "$erd" --dialect sqlite --strict --output "$tmp/note-store.sqlite.sql" 2>&1)"; then
  echo "$output" >&2
  exit 2
fi
render_swift "$tmp/note-store.sqlite.sql" > "$tmp/NoteStoreSchemaDDL.generated.swift"

if [[ "${1:-}" == "--check" ]]; then
  status=0
  cmp -s "$tmp/note-store.sqlite.sql" "$sql" || { echo "stale: schema/note-store.sqlite.sql" >&2; status=1; }
  cmp -s "$tmp/NoteStoreSchemaDDL.generated.swift" "$swift" \
    || { echo "stale: Sources/AppCore/NoteStoreSchemaDDL.generated.swift" >&2; status=1; }
  [[ $status -eq 0 ]] && echo "note-store schema is up to date"
  exit $status
fi

cp "$tmp/note-store.sqlite.sql" "$sql"
cp "$tmp/NoteStoreSchemaDDL.generated.swift" "$swift"
echo "wrote schema/note-store.sqlite.sql and Sources/AppCore/NoteStoreSchemaDDL.generated.swift"
